"""Table 9 -- structural conditions behind demographic transfer (Section 7.4).

* delta: Cliff's delta of coreness, group S0 vs S1
  (``experiments/coreness_by_group.py`` -> ``coreness_group_association.csv``);
* more core: group with the higher mean coreness;
* more exposed: group with the higher mean per-node HL-GNN exposure
  (``group_exposure.csv``, ``python experiments/summarize_exposure.py``);
* predicted change of DeltaSP: narrowing (down) when the more-core group is
  also the more-exposed one, widening (up) otherwise;
* paired DeltaSP differences: identical to Table 16(a).
"""
import statistics

from tables import t16_demographic_protocol as T16
from tables._demographic import DATASETS
from tables._common import resolve
from tables._common import DATASET_LABEL, cell, read_csv, tabular, write_text

ID = "T09"
ASSOC = "summaries/coreness_by_group/coreness_group_association.csv"
GROUPS = "summaries/coreness_by_group/group_exposure.csv"


def input_files():
    return [ASSOC, GROUPS] + T16.input_files()


def magnitude(d):
    d = abs(d)
    return "negligible" if d < 0.147 else "small" if d < 0.33 else "medium" if d < 0.474 else "large"


def build(out):
    assoc = {r["dataset"]: r for r in read_csv(resolve(ASSOC))}
    exposure = {}
    for r in read_csv(resolve(GROUPS)):
        if r["method"] == "HL-GNN":
            exposure.setdefault((r["dataset"], int(float(r["group"]))), []).append(float(r["exposure_mean"]))
    sp = {(c["dataset"], c["row"], c["column"]): c for c in T16.build(out) if c["panel"] == "dsp_e3"}
    cells, body = [], []
    for ds in DATASETS:
        a = assoc[ds]
        delta = float(a["cliffs_delta_g0_vs_g1"])
        core = "S0" if float(a["coreness_mean_g0"]) > float(a["coreness_mean_g1"]) else "S1"
        exposed = "S0" if statistics.fmean(exposure[(ds, 0)]) > statistics.fmean(exposure[(ds, 1)]) else "S1"
        pred = "↓" if core == exposed else "↑"
        cells += [cell(ID, ds, ds, "cliffs_delta", delta, None, 2, extra=magnitude(delta)),
                  cell(ID, ds, ds, "more_core", None, None, "", extra=core),
                  cell(ID, ds, ds, "more_exposed", None, None, "", extra=exposed),
                  cell(ID, ds, ds, "predicted", None, None, "", extra=pred)]
        for i, variant in enumerate(["CAFE-In", "CAFE-Pre"]):
            row = [DATASET_LABEL[ds] if i == 0 else ""]
            row += [f"${delta:+.2f}$ ({magnitude(delta)})", f"$S_{core[1]}$", f"$S_{exposed[1]}$",
                    "$\\downarrow$" if pred == "↓" else "$\\uparrow$"] if i == 0 else ["", "", "", ""]
            row.append(variant)
            for col, name in [("diff_vs_hlgnn", "vs_backbone"), ("diff_vs_fusion", "vs_fusion")]:
                c = sp[(ds, variant, col)]
                cells.append(cell(ID, ds, variant, name, c["mean"], c["sd"], 3, extra=c["extra"]))
                row.append(f"${c['mean']:+.3f} \\pm {c['sd']:.3f}$" + c["extra"])
            body.append(row)
    write_text("% Table 9 -- generated by `python -m tables T09`\n" +
               tabular(["Dataset", r"$\delta$ ($S_0$ vs. $S_1$)", "More core", "More exposed", "Pred.",
                        "Variant", "vs. backbone", "vs. fusion"], body, "lllllrrr"), out / f"{ID}.tex")
    return cells
