"""Table 5 -- realized source-coreness bins of the stratified profiles (Section 7.2)."""
from tables._stratified import FOCUS, input_files, load  # noqa: F401
from tables._common import DATASET_LABEL, cell, tabular, write_text

ID = "T05"
ORDER = ["ego-facebook", "oklahoma", "unc", "pokec_n", "brightkite"]


def build(out):
    mono = {r["dataset"]: r for r in load("bin_size_monotonicity") if r["model"] == FOCUS}
    summary = load("bin_perturbation_summary")
    cells, body = [], []
    for ds in ORDER:
        m = mono[ds]
        bins = [r for r in summary if r["dataset"] == ds]
        lo, hi = min(int(r["coreness_min"]) for r in bins), max(int(r["coreness_max"]) for r in bins)
        vals = dict(bins=int(m["n_bins"]), coreness_min=lo, coreness_max=hi, eval_users=int(m["eval_users"]),
                    min_bin=int(m["size_min"]), max_bin=int(m["size_max"]))
        cells += [cell(ID, ds, ds, k, float(v), None, 0) for k, v in vals.items()]
        rho = float(m["rho_size_vs_coreness"])
        cells.append(cell(ID, ds, ds, "rho_s", rho, None, 2))
        body.append([DATASET_LABEL[ds], str(vals["bins"]), f"{lo}--{hi}", f"{vals['eval_users']:,}",
                     f"{vals['min_bin']:,}", f"{vals['max_bin']:,}", f"${rho:+.2f}$"])
    write_text("% Table 5 -- generated by `python -m tables T05`\n" +
               tabular(["Dataset", "Bins", "Coreness", "Eval. users", "Min. bin size", "Max. bin size",
                        r"$\rho_S$"], body, "lrrrrrr"), out / f"{ID}.tex")
    return cells
