"""Table 17 -- Brightkite random-split control (Appendix B.1).

Ten connectivity-preserving random 85/5/10 splits (seeds 42-51); lowest and
highest source-coreness bin Precision@10 (split means), their paired
difference with a 95% t-interval, and the mean Spearman correlation between
stratified Degree EG and coreness rank.

Input: ``summaries/brightkite_random_control/
brightkite_random_control_summary.csv`` written by
``experiments/finalize_brightkite_random_control.py``.  Not part of the evidence
results: run ``experiments/run_stratified_cafe.py`` on ten random splits and
``experiments/finalize_brightkite_random_control.py`` (see README).
"""
from tables._common import exists, resolve
from tables._common import cell, read_csv, tabular, write_text

ID = "T17"
SUMMARY = "summaries/brightkite_random_control/brightkite_random_control_summary.csv"
LABEL = {"Fusion": "HL-GNN+RA"}


def input_files():
    return []  # produced by the job, not frozen


def build(out):
    if not exists(SUMMARY):
        write_text(f"% Table 17: {SUMMARY} not found -- run the Brightkite random-split control first (see README)\n",
                   out / f"{ID}.tex")
        return []
    cells, body = [], []
    for r in read_csv(resolve(SUMMARY)):
        name = LABEL.get(r["method"], r["method"])
        f = {k: float(v) for k, v in r.items() if k != "method"}
        vals = dict(lowest_p10=f["lowest_bin_precision_mean"], highest_p10=f["highest_bin_precision_mean"],
                    high_minus_low=f["high_minus_low_mean"], ci_low=f["high_minus_low_ci95_low"],
                    ci_high=f["high_minus_low_ci95_high"], rho_s_deg_eg=f["eg_coreness_spearman_rho_mean"])
        cells += [cell(ID, "brightkite", name, k, v, None, 2 if k == "rho_s_deg_eg" else 4) for k, v in vals.items()]
        body.append([r["method"], f"{vals['lowest_p10']:.4f}", f"{vals['highest_p10']:.4f}",
                     f"${vals['high_minus_low']:+.4f}$ [${vals['ci_low']:+.4f}$, ${vals['ci_high']:+.4f}$]",
                     f"${vals['rho_s_deg_eg']:+.2f}$"])
    write_text("% Table 17 -- generated by `python -m tables T17`\n" +
               tabular(["Method", "Lowest P@10", "Highest P@10", r"High$-$Low [95\% CI]", r"$\rho_S$ (Degree EG)"],
                       body, "lrrrr"), out / f"{ID}.tex")
    return cells
