"""Table 8 -- demographic fairness at K=10 (Section 7.4).

Fixed split; mean +- SD over 10 repetitions.  DeltaSP and DeltaEO are scaled
by 10^3.  Lower DeltaSP/DeltaEO is better.
"""
from tables._demographic import DATASETS, fixed_split, input_files  # noqa: F401
from tables._common import DATASET_LABEL, METHOD_LABEL, cell, decorate, emphasis, fmt, tabular, write_text

ID = "T08"
GROUPS = [("Backbone (attr.-free)", ["HL-GNN"]), ("Fairness (attr.-dep.)", ["FairAdj", "LBA", "MORAL"]),
          ("CAFE (attr.-free, ours)", ["HL-GNN+RA", "CAFE-P", "CAFE-In-B", "CAFE-Pre-B", "CAFE-In", "CAFE-Pre"])]
COLUMNS = [("prec", "prec", 4, 1.0, True), ("dsp_e3", "dsp", 3, 1e3, False), ("deo_e3", "deo", 1, 1e3, False)]


def build(out):
    fixed = fixed_split()
    cells, tex = [], []
    for letter, ds in zip("abc", DATASETS):
        ordered = [(g, m) for g, ms in GROUPS for m in ms]
        marks = {col: emphasis([fixed[(ds, m)][key][0] for _, m in ordered], higher_is_better=hi)
                 for col, key, _, _, hi in COLUMNS}
        body, last = [], None
        for i, (group, m) in enumerate(ordered):
            if last is not None and group != last:
                body.append("MIDRULE")
            row = [group if group != last else "", METHOD_LABEL.get(m, m)]
            for col, key, dec, scale, _ in COLUMNS:
                mean, sd = (v * scale for v in fixed[(ds, m)][key])
                cells.append(cell(ID, ds, m, col, mean, sd, dec))
                row.append(decorate(fmt(mean, sd, dec), marks[col].get(i)))
            body.append(row)
            last = group
        tex.append(rf"\subcaption*{{({letter}) {DATASET_LABEL[ds]}}}")
        tex.append(tabular(["Model Type", "Method", "Prec@10", r"$\Delta$SP@10 ($\times10^{-3}$)",
                            r"$\Delta$EO@10 ($\times10^{-3}$)"], body, "llrrr"))
    write_text("% Table 8 -- generated by `python -m tables T08`\n" + "\n".join(tex), out / f"{ID}.tex")
    return cells
