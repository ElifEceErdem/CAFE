"""Table 7 -- CAFE ablations at K=10 (Section 7.3).

Fixed split; mean +- population SD over 10 training seeds.  DeltaPrec is the
relative change of the unrounded mean Precision@10 against HL-GNN.
"""
from tables._main_rows import DECIMALS, load_rows, summaries, input_files  # noqa: F401
from tables._common import (DATASET_LABEL, DATASET_ORDER, METHOD_LABEL, cell, decorate, emphasis, fmt,
                             summary_cells, tabular, write_text)

ID = "T07"
GROUPS = [
    ("Backbone", ["HL-GNN"]),
    ("Single comp.", ["CI-In", "CI-Pre", "MB-Post", "HL-GNN+RA"]),
    ("Two-stage", ["CAFE-In-B", "CAFE-Pre-B", "CAFE-P"]),
    ("Full pipeline", ["CAFE-In", "CAFE-Pre"]),
]
COLUMNS = ["prec", "deg_eg", "pr_eg", "cl_eg"]
HEADER = ["Dataset", "Category", "Config", "Prec@10", r"$\Delta$Prec", "Deg EG", "PR EG", "Cl. EG"]


def build(out):
    rows = load_rows()
    cells, body = [], []
    for ds in DATASET_ORDER:
        ordered = [(g, m) for g, ms in GROUPS for m in ms]
        stats = {m: summaries(rows[(ds, m)]) for _, m in ordered}
        base = stats["HL-GNN"]["prec"]["mean"]
        marks = {c: emphasis([stats[m][c]["mean"] for _, m in ordered]) for c in COLUMNS}
        if body:
            body.append("MIDRULE")
        last = None
        for i, (group, m) in enumerate(ordered):
            cells += summary_cells(ID, ds, m, stats[m], DECIMALS)
            delta = None
            if m != "HL-GNN":
                delta = 100.0 * (stats[m]["prec"]["mean"] / base - 1.0)
                cells.append(cell(ID, ds, m, "dprec_pct", delta, None, 0))
            row = [DATASET_LABEL[ds] if i == 0 else "", group if group != last else "",
                   METHOD_LABEL.get(m, m) + (r" $\star$" if group == "Full pipeline" else "")]
            row.append(decorate(fmt(stats[m]["prec"]["mean"], stats[m]["prec"]["sd"], 4), marks["prec"].get(i)))
            row.append("--" if delta is None else f"{delta:+.0f}\\%")
            for c in COLUMNS[1:]:
                row.append(decorate(fmt(stats[m][c]["mean"], stats[m][c]["sd"], 2), marks[c].get(i)))
            body.append(row)
            last = group
    write_text("% Table 7 -- generated by `python -m tables T07`\n" +
               tabular(HEADER, body, "lllrrrrr"), out / f"{ID}.tex")
    return cells
