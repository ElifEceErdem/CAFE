"""Table 16 -- DeltaSP@10 and DeltaEO@10 under both protocols (Appendix B).

Absolute values: fixed split (mean +- SD over 10 training seeds) and
split-resampled (mean +- sample SD over 10 split seeds).  Paired columns: mean
CAFE-minus-reference difference +- 95% t half-width over the resampled splits,
Holm-corrected within each (measure, reference) family of six contrasts.
"""
import math

from scipy import stats as sps

from tables._demographic import DATASETS, fixed_split, input_files, mean_sd, resampled  # noqa: F401
from tables.t15_paired_contrasts import holm, stars
from tables._common import DATASET_LABEL, cell, tabular, write_text

ID = "T16"
MEASURES = [("dsp_e3", "dsp", "Delta_SP@10", 3), ("deo_e3", "deo", "Delta_EO@10", 2)]
METHODS = [("HL-GNN", "HL-GNN"), ("HL-GNN+RA", "Fusion"), ("CAFE-In", "CAFE-In"), ("CAFE-Pre", "CAFE-Pre")]
REFS = [("diff_vs_hlgnn", "HL-GNN"), ("diff_vs_fusion", "Fusion")]


def paired(res, ds, metric, variant, ref):
    a, b = res[(ds, variant, metric)], res[(ds, ref, metric)]
    diffs = [x - y for x, y in zip(a, b)]
    n = len(diffs)
    mean, sd = mean_sd(diffs)
    return mean, sps.t.ppf(0.975, n - 1) * sd / math.sqrt(n), sps.ttest_rel(a, b).pvalue


def build(out):
    fixed, res = fixed_split(), resampled()
    cells, tex = [], []
    for panel, key, metric, dec in MEASURES:
        contrasts = {}
        for col, ref in REFS:
            family = [(ds, v) for ds in DATASETS for v in ("CAFE-In", "CAFE-Pre")]
            vals = [paired(res, ds, metric, v, ref) for ds, v in family]
            for (ds, v), (m, h, _), p in zip(family, vals, holm([x[2] for x in vals])):
                contrasts[(col, ds, v)] = (m * 1e3, h * 1e3, stars(p))
        body = []
        for di, ds in enumerate(DATASETS):
            if di:
                body.append("MIDRULE")
            for mi, (label, key_resampled) in enumerate(METHODS):
                fm, fs = (x * 1e3 for x in fixed[(ds, label)][key])
                rm, rs = (x * 1e3 for x in mean_sd(res[(ds, key_resampled, metric)]))
                cells += [cell(ID, ds, label, "fixed_split", fm, fs, dec, panel=panel),
                          cell(ID, ds, label, "split_resampled", rm, rs, dec, panel=panel)]
                row = [DATASET_LABEL[ds] if mi == 0 else "", label,
                       f"${fm:.{dec}f} \\pm {fs:.{dec}f}$", f"${rm:.{dec}f} \\pm {rs:.{dec}f}$"]
                for col, _ in REFS:
                    if label in ("HL-GNN", "HL-GNN+RA"):
                        row.append("---")
                        continue
                    m, h, s = contrasts[(col, ds, label)]
                    cells.append(cell(ID, ds, label, col, m, h, dec, panel=panel, extra=s))
                    row.append(f"${m:+.{dec}f} \\pm {h:.{dec}f}$" + s)
                body.append(row)
        title = "(a) $\\Delta$SP@10 ($\\times10^{-3}$)" if key == "dsp" else "(b) $\\Delta$EO@10 ($\\times10^{-3}$)"
        tex.append(rf"\subcaption*{{{title}}}")
        tex.append(tabular(["Dataset", "Method", "Fixed split", "Split-resampled", "vs. HL-GNN", "vs. HL-GNN+RA"],
                           body, "llrrrr"))
    write_text("% Table 16 -- generated by `python -m tables T16`\n" + "\n".join(tex), out / f"{ID}.tex")
    return cells
