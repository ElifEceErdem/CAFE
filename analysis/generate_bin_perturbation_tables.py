"""Emit the LaTeX for the perturbation-size tables of Section 7.2.

Produces two files in --out_dir:

  table_coreness_bins.tex        drop-in replacement for Table 5, with the
                                 per-bin perturbation size K|B_g| and the
                                 Spearman correlation between bin size and
                                 coreness rank
  table_bin_perturbation.tex     appendix table: per-bin size, perturbation,
                                 and stratified Degree EG, plus the
                                 size-matched bin pairs

Inputs are the CSVs written by analysis/bin_perturbation_size.py, which reads
only the artifacts already backing Section 7.2. Nothing is retrained.
"""

import argparse
import os

import pandas as pd

# Presentation order used by the paper's Table 5.
DATASET_ORDER = ['ego-facebook', 'oklahoma', 'unc', 'pokec_n', 'brightkite']
DATASET_LABEL = {
    'ego-facebook': 'Ego-FB',
    'oklahoma': 'Oklahoma',
    'unc': 'UNC',
    'pokec_n': 'Pokec-n',
    'brightkite': 'Brightkite',
}


def argument():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--in_dir', default='analysis/plots/bin_perturbation')
    parser.add_argument('--out_dir', default='results_repro/tables')
    parser.add_argument('--focus_model', default='CAFE-In')
    return parser.parse_args()


def fmt(value):
    return f"{int(value):,}"


def signed(value, digits=2):
    return f"${value:+.{digits}f}$"


def table_coreness_bins(mono, focus_model):
    head = mono[mono['model'] == focus_model].set_index('dataset')
    lines = [
        r'% Auto-generated by analysis/generate_bin_perturbation_tables.py'
        r' -- do not edit by hand.',
        r'\begin{table}[t]',
        r'\caption{Realized coreness bins for the stratified profiles of',
        r'Section~\ref{sec:stratified-cure}. Ten equal-frequency quantiles are',
        r'requested; ties in the integer coreness values collapse some of them.',
        r'Bin $g$ issues $K|B_g|$ recommendations into $\hat{G}_g$, so the',
        r'$K|B_g|$ columns give the size of the perturbation whose effect',
        r'$\mathrm{EG}^{(g)}$ measures; they bound the number of distinct',
        r'undirected edges added, which is smaller only by the within-bin',
        r'reciprocal recommendations. $\rho_S$ is the Spearman correlation',
        r'between bin size and coreness rank. On no dataset is bin size',
        r'monotone in coreness, so a monotone cross-bin EG gradient cannot be',
        r'a perturbation-size gradient.}',
        r'\label{tab:coreness-bins}',
        r'\centering\small',
        r'\begin{tabular}{lrrrrrrrr}',
        r'\toprule',
        r' & & & & \multicolumn{2}{c}{Bin size $|B_g|$}'
        r' & \multicolumn{2}{c}{Recs.\ $K|B_g|$} & \\',
        r'\cmidrule(lr){5-6}\cmidrule(lr){7-8}',
        r'Dataset & Bins & Coreness & Eval.\ users & Min & Max & Min & Max'
        r' & $\rho_S$ \\',
        r'\midrule',
    ]
    for dataset in DATASET_ORDER:
        row = head.loc[dataset]
        lines.append(
            f"{DATASET_LABEL[dataset]} & {int(row['n_bins'])} & "
            f"{row['coreness_range']} & {fmt(row['eval_users'])} & "
            f"{fmt(row['size_min'])} & {fmt(row['size_max'])} & "
            f"{fmt(row['rec_min'])} & {fmt(row['rec_max'])} & "
            f"{signed(row['rho_size_vs_coreness'])} \\\\"
        )
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    return '\n'.join(lines)


def table_bin_perturbation(summary, mono, pairs, focus_model):
    eg_col = f'eg_{focus_model}'
    lines = [
        r'% Auto-generated by analysis/generate_bin_perturbation_tables.py'
        r' -- do not edit by hand.',
        r'\begin{table*}[t]',
        r'\caption{Perturbation size is not what drives the stratified'
        r' Degree-EG gradient.',
        r'Panel~(a) gives, per source-coreness bin, the evaluated users'
        r' $|B_g|$, the recommendations $K|B_g|$ that bin $g$ contributes to'
        r' $\hat{G}_g$, and ' + focus_model + r"'s stratified Degree~EG@10.",
        r'Panel~(b) contrasts the Spearman correlation of EG with coreness'
        r' rank against its correlation with perturbation size, and reports'
        r' the size-matched bin pair -- the two bins whose perturbations are'
        r' closest -- with the widest EG gap on each dataset.',
        r'Same fixed-split artifacts as Table~\ref{tab:coreness-bins};'
        r' descriptive, no per-bin hypothesis tests.}',
        r'\label{tab:bin-perturbation}',
        r'\centering\small',
        r'\subcaption*{(a) Per-bin perturbation and stratified Degree~EG@10}',
    ]

    for dataset in DATASET_ORDER:
        block = summary[summary['dataset'] == dataset].sort_values('coreness_bin')
        lines += [
            r'\par\smallskip',
            r'\begin{tabular}{l' + 'r' * len(block) + r'}',
            r'\toprule',
            (f"{DATASET_LABEL[dataset]} coreness & "
             + ' & '.join(row['coreness_bin_label'].replace('-', '--')
                          for _, row in block.iterrows()) + r' \\'),
            r'\midrule',
            (r'$|B_g|$ & '
             + ' & '.join(fmt(v) for v in block['n_users']) + r' \\'),
            (r'$K|B_g|$ & '
             + ' & '.join(fmt(v) for v in block['rec_events']) + r' \\'),
            (r'Deg EG@10 & '
             + ' & '.join(f"${v:+.2f}$" for v in block[eg_col]) + r' \\'),
            r'\bottomrule',
            r'\end{tabular}',
        ]

    lines += [
        r'\vspace{8pt}',
        r'\subcaption*{(b) Coreness versus size, and the widest size-matched'
        r' pair}',
        r'\begin{tabular}{lrrrlrrr}',
        r'\toprule',
        r' & \multicolumn{3}{c}{Spearman $\rho_S$ with EG$^{(g)}$}'
        r' & \multicolumn{4}{c}{Widest size-matched bin pair} \\',
        r'\cmidrule(lr){2-4}\cmidrule(lr){5-8}',
        r'Dataset & Coreness rank & $K|B_g|$ & size vs.\ rank'
        r' & Bins & $K|B_g|$ & EG@10 & Gap \\',
        r'\midrule',
    ]
    focus = mono[mono['model'] == focus_model].set_index('dataset')
    widest = pairs.loc[pairs.groupby('dataset')['eg_gap'].idxmax()].set_index('dataset')
    for dataset in DATASET_ORDER:
        row = focus.loc[dataset]
        pair = widest.loc[dataset]
        lines.append(
            f"{DATASET_LABEL[dataset]} & {signed(row['rho_eg_vs_coreness'])} & "
            f"{signed(row['rho_eg_vs_size'])} & "
            f"{signed(row['rho_size_vs_coreness'])} & "
            f"{pair['label_a'].replace('-', '--')} vs.\\ "
            f"{pair['label_b'].replace('-', '--')} & "
            f"{fmt(pair['rec_a'])} vs.\\ {fmt(pair['rec_b'])} & "
            f"${pair['eg_a']:+.2f}$ vs.\\ ${pair['eg_b']:+.2f}$ & "
            f"{pair['eg_gap']:.2f} \\\\"
        )
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{table*}', '']
    return '\n'.join(lines)


def main():
    args = argument()
    os.makedirs(args.out_dir, exist_ok=True)
    summary = pd.read_csv(os.path.join(args.in_dir,
                                       'bin_perturbation_summary.csv'))
    mono = pd.read_csv(os.path.join(args.in_dir, 'bin_size_monotonicity.csv'))
    pairs = pd.read_csv(os.path.join(args.in_dir, 'bin_size_matched_pairs.csv'))

    ranges = (summary.groupby('dataset')
                     .agg(lo=('coreness_min', 'min'), hi=('coreness_max', 'max')))
    mono['coreness_range'] = [
        f"{int(ranges.loc[d, 'lo'])}--{int(ranges.loc[d, 'hi'])}"
        for d in mono['dataset']
    ]

    outputs = {
        'table_coreness_bins.tex': table_coreness_bins(mono, args.focus_model),
        'table_bin_perturbation.tex': table_bin_perturbation(
            summary, mono, pairs, args.focus_model),
    }
    for name, body in outputs.items():
        path = os.path.join(args.out_dir, name)
        with open(path, 'w') as handle:
            handle.write(body)
        print(f"wrote {path}")


if __name__ == '__main__':
    main()
