"""
Merged RQ4 ablation table: one table covering all five datasets, replacing
the former Oklahoma-only table3 + four-dataset table6 pair.

Reads the per-dataset CSVs emitted by generate_ablation_tables.py (which
already contain the LaTeX-formatted cells, including per-dataset
bold/underline marks) and re-groups rows by stage count:

  Backbone      HL-GNN                      (0 CAFE stages)
  Single comp.  CI-In, CI-Pre, MB-Post,     (1 stage: penalty / penalty /
                HL-GNN+RA                    boost / RA fusion)
  Two-stage     CAFE-In-B, CAFE-Pre-B,      (full pipeline minus boost /
                CAFE-P                       minus boost / minus penalty)
  Full pipeline CAFE-In, CAFE-Pre           (all 3 stages)

HL-GNN+RA is relabelled from "HL-GNN+RA (CAFE^{-P,-B})": under the
stage-count taxonomy it is a single component (fusion alone), and it is
also the fusion-only control of the paired experiments.

Usage:
    python generate_merged_ablation_table.py \
        --tables_dir ../results_repro/tables \
        --out ../results_repro/tables/ablation_merged.tex
"""

import argparse
import os

import pandas as pd

DATASET_ORDER = ['brightkite', 'ego-facebook', 'oklahoma', 'pokec_n', 'unc']
DATASET_TEX = {'brightkite': 'Brightkite', 'ego-facebook': 'Ego-FB',
               'oklahoma': 'Oklahoma', 'pokec_n': 'Pokec-n', 'unc': 'UNC'}
# (method key in CSV, display label, category) in merged-table order
ROW_SPEC = [
    ('HLGNN',      r'HL-GNN',            'Backbone'),
    ('CI-In',      r'CI-In',             'Single comp.'),
    ('CI-Pre',     r'CI-Pre',            'Single comp.'),
    ('MB-Post',    r'MB-Post',           'Single comp.'),
    ('HLGNN+RA',   r'HL-GNN+RA',         'Single comp.'),
    ('CAFE-In-B',  r'CAFE-In$^{-B}$',    'Two-stage'),
    ('CAFE-Pre-B', r'CAFE-Pre$^{-B}$',   'Two-stage'),
    ('CAFE-P',     r'CAFE$^{-P}$',       'Two-stage'),
    ('CAFE-In',    r'CAFE-In $\star$',   'Full pipeline'),
    ('CAFE-Pre',   r'CAFE-Pre $\star$',  'Full pipeline'),
]
METRIC_COLS = ['Prec@10', 'dprec', 'Deg EG', 'PR EG', 'Cl. EG']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tables_dir', type=str, default='../results_repro/tables')
    ap.add_argument('--out', type=str,
                    default='../results_repro/tables/ablation_merged.tex')
    args = ap.parse_args()

    t3 = pd.read_csv(os.path.join(args.tables_dir, 'table3_ablation_oklahoma.csv'))
    t3['dataset'] = 'oklahoma'
    t6 = pd.read_csv(os.path.join(args.tables_dir, 'table6_ablation_all.csv'))
    df = pd.concat([t3, t6], ignore_index=True)

    lines = ['% Auto-generated by analysis/generate_merged_ablation_table.py '
             '-- do not edit by hand.',
             '\\begin{tabular}{lllrrrrr}',
             '\\toprule',
             'Dataset & Category & Config & Prec@10 & $\\Delta$Prec & '
             'Deg EG & PR EG & Cl.\\ EG \\\\',
             '\\midrule']
    for i, ds in enumerate(DATASET_ORDER):
        if i:
            lines.append('\\midrule')
        sub = df[df.dataset == ds].set_index('method')
        prev_cat, first_row = None, True
        for key, label, cat in ROW_SPEC:
            if key not in sub.index:
                continue
            r = sub.loc[key]
            if cat != prev_cat and prev_cat is not None:
                lines.append('\\addlinespace[2pt]')
            ds_cell = DATASET_TEX[ds] if first_row else ''
            cat_cell = cat if cat != prev_cat else ''
            cells = ' & '.join(str(r[c]) for c in METRIC_COLS)
            lines.append(f'{ds_cell} & {cat_cell} & {label} & {cells} \\\\')
            prev_cat, first_row = cat, False
    lines += ['\\bottomrule', '\\end{tabular}']

    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    print(f'\nWritten to {args.out}')


if __name__ == '__main__':
    main()
