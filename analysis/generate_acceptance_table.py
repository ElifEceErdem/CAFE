"""
RQ6 table: EG under full, precision-weighted (PW), and true-positive (TP)
acceptance, from the per-run CSVs written by
experiments/run_exposure_acceptance.py.

Emits two LaTeX fragments:

  --out      tab:acceptance -- one row per (dataset, method): Degree and
             PageRank EG under full and PW acceptance, Closeness EG under
             full and TP (PW is undefined for closeness; TP for
             Degree/PageRank is summarized in the text, not tabulated).

  --rho_out  tab:acceptance-weights -- the empirical rank precisions
             rho(r) that define the PW weighting, per dataset and rank,
             averaged over methods and reruns.  These were quoted in the
             RQ6 text without a table to point at.

Cells are mean +/- std over the fixed-split training-seed reruns present
in the input CSVs (currently n=10, except Pokec-n at n=3 -- the generator
reports the counts it found, so check them against the caption).

Usage:
    python generate_acceptance_table.py \
        --input_glob '../results/*/acceptance_eg/acceptance_eg_*.csv' \
        --out ../results_repro/tables/acceptance_table.tex \
        --rho_out ../results_repro/tables/acceptance_weights_table.tex
"""

import argparse
import glob

import pandas as pd

DATASET_TEX = {'brightkite': 'Brightkite', 'ego-facebook': 'Ego-FB',
               'oklahoma': 'Oklahoma', 'pokec_n': 'Pokec-n', 'unc': 'UNC'}
DATASET_ORDER = ['brightkite', 'ego-facebook', 'oklahoma', 'pokec_n', 'unc']
METHOD_ORDER = ['RA', 'HL-GNN', 'HL-GNN+RA', 'CAFE-In', 'CAFE-Pre']
COLUMNS = [('Degree_EG@10', 'full'), ('Degree_EG@10', 'pw'),
           ('Pagerank_EG@10', 'full'), ('Pagerank_EG@10', 'pw'),
           ('Closeness_EG@10', 'full'), ('Closeness_EG@10', 'tp')]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--input_glob', type=str,
                    default='../results/*/acceptance_eg/acceptance_eg_*.csv')
    ap.add_argument('--out', type=str, default='acceptance_table.tex')
    ap.add_argument('--rho_out', type=str, default='acceptance_weights_table.tex')
    args = ap.parse_args()

    files = sorted(glob.glob(args.input_glob))
    if not files:
        raise SystemExit(f'No input files matched: {args.input_glob}')
    df = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)

    agg = df.groupby(['dataset', 'method', 'metric'])['value'] \
            .agg(['mean', 'std', 'count'])

    def cell(ds, m, base, variant):
        try:
            r = agg.loc[(ds, m, f'{base}_{variant}')]
        except KeyError:
            return '--'
        return f"{r['mean']:.2f} $\\pm$ {r['std']:.2f}"

    lines = ['% Auto-generated by analysis/generate_acceptance_table.py '
             '-- do not edit by hand.',
             '\\begin{tabular}{llrrrrrr}',
             '\\toprule',
             ' & & \\multicolumn{2}{c}{Deg EG@10} & '
             '\\multicolumn{2}{c}{PR EG@10} & '
             '\\multicolumn{2}{c}{Cl.\\ EG@10} \\\\',
             '\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}',
             'Dataset & Method & Full & PW & Full & PW & Full & TP \\\\',
             '\\midrule']
    for i, ds in enumerate(DATASET_ORDER):
        if i:
            lines.append('\\midrule')
        for j, m in enumerate(METHOD_ORDER):
            lead = DATASET_TEX[ds] if j == 0 else ''
            cells = ' & '.join(cell(ds, m, b, v) for b, v in COLUMNS)
            lines.append(f'{lead} & {m} & {cells} \\\\')
    lines += ['\\bottomrule', '\\end{tabular}']

    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    print(f'\nWritten to {args.out}')
    n = agg['count'].unique()
    print(f'Run counts present in data: {sorted(n)}')

    write_rho_table(df, args.rho_out)


# ---------------------------------------------------------------- rho table
RHO_RANKS = list(range(1, 11))


def write_rho_table(df, out_path):
    """tab:acceptance-weights: empirical rank precision rho(r).

    rho(r) is a property of a scorer's ranking, so it varies by method; the
    RQ6 text quotes one number per (dataset, rank), which is the mean over
    all five evaluated methods and all reruns.  That is what this table
    reports, with the across-method spread as the +/- term so the
    method-dependence stays visible.
    """
    rho = df[df['metric'].str.startswith('rho_rank_')].copy()
    if rho.empty:
        print('No rho_rank_* rows found; skipping the acceptance-weights table.')
        return
    rho['rank'] = rho['metric'].str.replace('rho_rank_', '').astype(int)

    lines = ['% Auto-generated by analysis/generate_acceptance_table.py '
             '-- do not edit by hand.',
             '\\begin{tabular}{l' + 'r' * len(RHO_RANKS) + '}',
             '\\toprule',
             'Dataset & ' + ' & '.join(str(r) for r in RHO_RANKS) + ' \\\\',
             '\\midrule']
    csv_rows = []
    for ds in DATASET_ORDER:
        sub = rho[rho['dataset'] == ds]
        if sub.empty:
            continue
        cells = []
        for r in RHO_RANKS:
            at_r = sub[sub['rank'] == r]
            # average within method first so unequal rerun counts cannot
            # tilt the across-method mean
            per_method = at_r.groupby('method')['value'].mean()
            cells.append(f'{per_method.mean():.3f}')
            csv_rows.append(dict(dataset=ds, rank=r,
                                 rho_mean=per_method.mean(),
                                 rho_min=per_method.min(),
                                 rho_max=per_method.max(),
                                 n_methods=len(per_method),
                                 n_runs=at_r['run'].nunique()))
        lines.append(f'{DATASET_TEX[ds]} & ' + ' & '.join(cells) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}']

    with open(out_path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    print(f'\nWritten to {out_path}')

    stats = pd.DataFrame(csv_rows)
    csv_path = out_path.replace('.tex', '.csv')
    stats.to_csv(csv_path, index=False)
    print(f'Written to {csv_path}')
    r1 = stats[stats['rank'] == 1].set_index('dataset')['rho_mean']
    r10 = stats[stats['rank'] == 10].set_index('dataset')['rho_mean']
    print(f"rho(1)  range: {r1.min():.3f} ({r1.idxmin()}) "
          f"to {r1.max():.3f} ({r1.idxmax()})")
    print(f"rho(10) range: {r10.min():.3f} ({r10.idxmin()}) "
          f"to {r10.max():.3f} ({r10.idxmax()})")


if __name__ == '__main__':
    main()
