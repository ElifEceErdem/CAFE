"""Table 10 -- mobility-boost effect on predicted target closeness (Section 7.5).

Input: ``results_repro/tables/closeness_strata.csv`` written by
``analysis/generate_closeness_stratum_table.py`` from the paired probe runs
(``analysis/closeness_mechanism.py``); job ``t10_closeness_probe.job``.
Entries are paired changes HL-GNN+RA+boost minus HL-GNN+RA over 10 reruns.
"""
from collections import defaultdict

from reproduce.paths import resolve
from reproduce.table import DATASET_LABEL, cell, read_csv, tabular, write_text

ID = "T10"
INPUT = "results_repro/tables/closeness_strata.csv"


def input_files():
    return [INPUT]


def build(out):
    rows = read_csv(resolve(INPUT))
    by = defaultdict(dict)
    for r in rows:  # the deployed-dose rows appear twice (probe + dose sweep); keep one per bin
        by[(r["dataset"], float(r["lambda_mob"]))][int(r["bin"])] = r
    cells, body_a, body_b = [], [], []
    for ds in ["ego-facebook", "oklahoma", "unc"]:
        block = [by[(ds, 0.5)][b] for b in sorted(by[(ds, 0.5)])]
        q = [float(r["delta_mean"]) for r in block]
        g0, g1, e0, e1 = (float(block[0][k]) for k in ("gini_control", "gini_arm", "eg_control", "eg_arm"))
        for i, v in enumerate(q, 1):
            cells.append(cell(ID, ds, ds, f"q{i}", v, None, 4, panel="a"))
        cells += [cell(ID, ds, ds, "gini_control", g0, None, 4, panel="a"),
                  cell(ID, ds, ds, "gini_boost", g1, None, 4, panel="a"),
                  cell(ID, ds, ds, "cl_eg_control", e0, None, 2, panel="a"),
                  cell(ID, ds, ds, "cl_eg_boost", e1, None, 2, panel="a")]
        body_a.append([DATASET_LABEL[ds]] + [f"${v:+.4f}$" for v in q] +
                      [f"{g0:.4f} $\\to$ {g1:.4f}", f"{e0:.2f} $\\to$ {e1:.2f}"])
    control = None
    for lam in sorted(k[1] for k in by if k[0] == "ego-facebook"):
        block = [by[("ego-facebook", lam)][b] for b in sorted(by[("ego-facebook", lam)])]
        q = [float(r["delta_mean"]) for r in block]
        gini, eg = float(block[0]["gini_arm"]), float(block[0]["eg_arm"])
        control = (float(block[0]["gini_control"]), float(block[0]["eg_control"]))
        row = f"lambda_{lam:g}" if lam != 1 else "lambda_1.0"
        for i, v in enumerate(q, 1):
            cells.append(cell(ID, "ego-facebook", row, f"q{i}", v, None, 4, panel="b"))
        cells += [cell(ID, "ego-facebook", row, "gini", gini, None, 4, panel="b"),
                  cell(ID, "ego-facebook", row, "cl_eg", eg, None, 2, panel="b")]
        body_b.append([f"{lam:g}"] + [f"${v:+.4f}$" for v in q] + [f"{gini:.4f}", f"{eg:.2f}"])
    cells += [cell(ID, "ego-facebook", "control", "gini", control[0], None, 4, panel="b"),
              cell(ID, "ego-facebook", "control", "cl_eg", control[1], None, 2, panel="b")]
    body_b.append([r"\emph{control} ($+$RA)"] + ["---"] * 5 + [f"{control[0]:.4f}", f"{control[1]:.2f}"])
    head = ["Q1 (periph.)", "Q2", "Q3", "Q4", "Q5 (core)"]
    write_text("% Table 10 -- generated by `python -m reproduce build T10`\n" +
               tabular(["Dataset"] + head + ["Gini", "Cl. EG@10"], body_a, "lrrrrrrr") +
               tabular([r"$\lambda_{\mathrm{mob}}$"] + head + ["Gini", "Cl. EG@10"], body_b, "lrrrrrrr"),
               out / f"{ID}.tex")
    return cells
