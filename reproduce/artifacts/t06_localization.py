"""Table 6 -- CAFE-In versus the fusion control (HL-GNN+RA at CAFE-In's beta), Section 7.2.

(a) Source side: lowest source-coreness bin, CAFE-In minus fusion Precision@10
    (paired within rerun) and the lowest/highest-bin precision ratio.  Needs the
    stratified per-user precision of ``analysis/run_stratified_cafe.py`` (10 reruns) with
    ``--include_fusion True`` (``stratified_cafe_<ds>.csv``); built only when
    those files are present (job ``t06_localization.job``).
(b) Target side: relative change of mean per-node exposure per target-coreness
    tercile, averaged over reruns (paired), from ``tier_exposure.csv``
    (``python -m reproduce.tools.derive_exposure``).
"""
from reproduce.paths import exists, resolve
from reproduce.table import DATASET_LABEL, DATASET_ORDER, cell, read_csv, tabular, write_text

ID = "T06"
TIERS_FILE = "analysis/plots/coreness_by_group/tier_exposure.csv"
STRATIFIED = "results_repro/localization/stratified_cafe_{ds}.csv"  # written by reproduce/jobs/t06_localization.job
TIERS = ["periphery", "middle", "core"]


def input_files():
    return [TIERS_FILE]


def panel_a(ds):
    import pandas as pd
    df = pd.read_csv(resolve(STRATIFIED.format(ds=ds)), usecols=["model", "precision", "run", "coreness_bin"])
    lo, hi = df.coreness_bin.min(), df.coreness_bin.max()
    per_run = df.groupby(["model", "run", "coreness_bin"])["precision"].mean()
    low = per_run.xs(lo, level="coreness_bin").unstack("model")
    high = per_run.xs(hi, level="coreness_bin").unstack("model")
    fusion = "Fusion" if "Fusion" in low else "HL-GNN+RA"
    diff = (low["CAFE-In"] - low[fusion]).dropna()
    return (diff.mean(), diff.std(ddof=1), low[fusion].mean() / high[fusion].mean(),
            low["CAFE-In"].mean() / high["CAFE-In"].mean(), len(diff))


def build(out):
    cells, body_a, body_b = [], [], []
    for ds in DATASET_ORDER:
        if exists(STRATIFIED.format(ds=ds)):
            d, s, rf, rc, n = panel_a(ds)
            if n > 1:
                cells += [cell(ID, ds, ds, "dprec_lowest_bin", d, s, 4, panel="a"),
                          cell(ID, ds, ds, "ratio_fusion", rf, None, 3, panel="a"),
                          cell(ID, ds, ds, "ratio_cafe_in", rc, None, 3, panel="a")]
                body_a.append([DATASET_LABEL[ds], f"${d:+.4f} \\pm {s:.4f}$", f"{rf:.3f} $\\to$ {rc:.3f}"])

    rows = [r for r in read_csv(resolve(TIERS_FILE)) if r["method"] in ("HL-GNN+RA", "CAFE-In")]
    for ds in DATASET_ORDER:
        by = {}
        for r in rows:
            if r["dataset"] == ds:
                by[(r["run"], r["method"], r["tier"])] = float(r["exposure_mean"])
        runs = sorted({k[0] for k in by})
        line = [DATASET_LABEL[ds]]
        for tier in TIERS:
            pairs = [(by[(k, "CAFE-In", tier)], by[(k, "HL-GNN+RA", tier)]) for k in runs
                     if (k, "CAFE-In", tier) in by and (k, "HL-GNN+RA", tier) in by]
            rel = sum(100 * (c / f - 1) for c, f in pairs if f > 0) / len([p for p in pairs if p[1] > 0])
            absolute = sum(c - f for c, f in pairs) / len(pairs)
            cells += [cell(ID, ds, ds, f"rel_{tier}", rel, None, 1, panel="b"),
                      cell(ID, ds, ds, f"abs_{tier}", absolute, None, "", panel="b")]
            line.append(f"${rel:+.1f}\\%$ (${absolute:+.2e}$)")
        body_b.append(line)
    tex = "% Table 6 -- generated by `python -m reproduce build T06`\n"
    if body_a:
        tex += tabular(["Dataset", r"$\Delta$Precision@10", r"$P_{low}/P_{high}$: Fusion $\to$ CAFE-In"],
                       body_a, "lrr")
    else:
        tex += "% Panel (a): stratified fusion runs not available -- run reproduce/jobs/t06_localization.job\n"
    tex += tabular(["Dataset", "Peripheral tercile", "Middle tercile", "Core tercile"], body_b, "lrrr")
    write_text(tex, out / f"{ID}.tex")
    return cells
