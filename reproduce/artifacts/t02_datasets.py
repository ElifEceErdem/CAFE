"""Table 2 -- dataset statistics (Section 6.1).

Input: ``results_repro/tables/dataset_table.csv`` written by
``analysis/generate_dataset_table.py`` from the processed graphs
(the job ``t02_datasets.job`` regenerates it).  "Avg. cluster." is the
global transitivity.
"""
from reproduce.paths import resolve
from reproduce.table import DATASET_LABEL, cell, read_csv, tabular, write_text

ID = "T02"
INPUT = "results_repro/tables/dataset_table.csv"
ORDER = ["ego-facebook", "oklahoma", "unc", "pokec_n", "brightkite"]


def input_files():
    return [INPUT]


def build(out):
    rows = {r["dataset"]: r for r in read_csv(resolve(INPUT))}
    cells, body = [], []
    for ds in ORDER:
        r = rows[ds]
        attr = {"---": "none"}.get(r["attribute"], r["attribute"])
        cells += [cell(ID, ds, ds, "nodes", float(r["num_nodes"]), None, 0),
                  cell(ID, ds, ds, "edges", float(r["num_edges"]), None, 0),
                  cell(ID, ds, ds, "avg_degree", float(r["avg_degree"]), None, 2),
                  cell(ID, ds, ds, "avg_clustering", float(r["transitivity"]), None, 2),
                  cell(ID, ds, ds, "attribute", None, None, "", extra=attr)]
        body.append([DATASET_LABEL[ds], f"{int(r['num_nodes']):,}", f"{int(r['num_edges']):,}",
                     f"{float(r['avg_degree']):.2f}", f"{float(r['transitivity']):.2f}",
                     "---" if attr == "none" else attr])
    write_text("% Table 2 -- generated by `python -m reproduce build T02`\n" +
               tabular(["Dataset", "$|V|$", "$|E|$", "Avg. deg.", "Avg. cluster.", "Attr."], body, "lrrrrl"),
               out / f"{ID}.tex")
    return cells
