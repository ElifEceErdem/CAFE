"""Table 4 -- Precision@10 and Equality Gain@10 for every method (Section 7.1).

Fixed split; mean +- population SD over the recorded runs (10 per learned
method, 1 per deterministic heuristic; the nine learned Pokec-n baselines have
8 runs).  Bold/underline: highest and second-highest distinct unrounded mean
per column within a dataset panel.
"""
from reproduce.artifacts._main_rows import DECIMALS, DETERMINISTIC, load_rows, summaries, input_files  # noqa: F401
from reproduce.table import (DATASET_LABEL, DATASET_ORDER, decorate, emphasis, fmt, summary_cells,
                             tabular, write_text)

ID = "T04"
ATTRIBUTED = {"oklahoma", "pokec_n", "unc"}
GROUPS = [
    ("Heuristic", ["Random", "PA", "RA", "AA", "CN"]),
    ("GNN Backbone", ["LightGCN", "SSNet", "HL-GNN"]),
    ("Fairness (attr.-free)", ["Cross-LinkBias"]),
    ("Fairness (attr.-dep.)", ["FairAdj", "LBA", "MORAL"]),
    (r"Deg./Bias Mit.\ (attr.-free)", ["LTLP", "TailSTEAK"]),
    ("CAFE (ours)", ["CAFE-In", "CAFE-Pre"]),
]
COLUMNS = ["prec", "deg_eg", "pr_eg", "cl_eg"]
HEADER = ["Model Type", "Method", "Prec@10", "Deg EG@10", "PR EG@10", "Cl. EG@10"]


def panel_methods(ds):
    for group, methods in GROUPS:
        kept = [m for m in methods if not (group.startswith("Fairness (attr.-dep") and ds not in ATTRIBUTED)]
        if kept:
            yield group, kept


def build(out):
    rows = load_rows()
    cells, tex = [], []
    for letter, ds in zip("abcde", DATASET_ORDER):
        ordered = [(g, m) for g, ms in panel_methods(ds) for m in ms]
        stats = {m: summaries(rows[(ds, m)]) for _, m in ordered}
        for _, m in ordered:
            cells += summary_cells(ID, ds, m, stats[m], DECIMALS, deterministic=m in DETERMINISTIC)
        marks = {c: emphasis([stats[m][c]["mean"] for _, m in ordered]) for c in COLUMNS}
        body, last = [], None
        for i, (group, m) in enumerate(ordered):
            if last is not None and group != last:
                body.append("MIDRULE")
            det = m in DETERMINISTIC
            row = [group if group != last else "", m]
            for c in COLUMNS:
                s = stats[m][c]
                row.append(decorate(fmt(s["mean"], None if det else s["sd"], DECIMALS[c]), marks[c].get(i)))
            body.append(row)
            last = group
        tex.append(rf"\subcaption*{{({letter}) {DATASET_LABEL[ds]}}}")
        tex.append(tabular(HEADER, body, "llrrrr"))
    write_text("% Table 4 -- generated by `python -m reproduce build T04`\n" + "\n".join(tex), out / f"{ID}.tex")
    return cells
