"""Table 18 -- bin size, degree and clustering do not drive the EG gradient (Appendix C).

(a) per-bin size and CAFE-In stratified Degree EG; (c) the most size-matched
pair of bins -- both from ``analysis/plots/bin_perturbation`` (see
``_stratified``).  (b) Spearman correlations of the per-bin EG with alternative
stratifiers and the within-degree-band range -- from
``results_rq1_controls/structural_controls_v1/finalized``.
"""
from reproduce.artifacts import _stratified as S
from reproduce.paths import resolve
from reproduce.table import DATASET_LABEL, cell, read_csv, tabular, write_text

ID = "T18"
ORDER = ["ego-facebook", "oklahoma", "unc", "pokec_n", "brightkite"]
RQ1 = "results_rq1_controls/structural_controls_v1/finalized"
AXES = f"{RQ1}/rq1_axis_correlations_on_mean_eg.csv"
BANDS = f"{RQ1}/rq1_nested_within_degree_summary.csv"


def input_files():
    return S.input_files() + [AXES, BANDS]


def build(out):
    summary = S.load("bin_perturbation_summary")
    mono = {r["dataset"]: r for r in S.load("bin_size_monotonicity") if r["model"] == S.FOCUS}
    pairs = [r for r in S.load("bin_size_matched_pairs") if r["model"] == S.FOCUS]
    axes = {(r["dataset"], r["axis"]): float(r["spearman_rho_on_mean_eg"])
            for r in read_csv(resolve(AXES)) if r["method"] == S.FOCUS}
    bands = {r["dataset"]: r for r in read_csv(resolve(BANDS)) if r["method"] == S.FOCUS}
    cells, tex = [], []

    for ds in ORDER:
        bins = sorted((r for r in summary if r["dataset"] == ds), key=lambda r: int(r["coreness_bin"]))
        header = [f"{DATASET_LABEL[ds]} coreness"] + [r["coreness_bin_label"].replace("-", "--") for r in bins]
        sizes = ["$|B_g|$"] + [f"{int(r['n_users']):,}" for r in bins]
        egs = ["Deg EG@10"] + [f"${float(r['eg_' + S.FOCUS]):+.2f}$" for r in bins]
        for r in bins:
            lab = S.label(r["coreness_bin_label"])
            cells.append(cell(ID, ds, lab, "bin_size", float(r["n_users"]), None, 0, panel="a"))
            cells.append(cell(ID, ds, lab, "deg_eg", float(r["eg_" + S.FOCUS]), None, 2, panel="a"))
        tex.append(tabular(header, [sizes, egs], "l" + "r" * len(bins)))

    body_b = []
    for ds in ORDER:
        vals = dict(rho_coreness=axes[(ds, "coreness")], rho_degree=axes[(ds, "degree")],
                    rho_clustering=axes[(ds, "clustering")], rho_bin_size=float(mono[ds]["rho_eg_vs_size"]),
                    within_band_min=float(bands[ds]["rho_min"]), within_band_max=float(bands[ds]["rho_max"]))
        cells += [cell(ID, ds, ds, k, v, None, 2, panel="b") for k, v in vals.items()]
        body_b.append([DATASET_LABEL[ds]] + [f"${vals[k]:+.2f}$" for k in
                                              ("rho_coreness", "rho_degree", "rho_clustering", "rho_bin_size")]
                      + [f"$[{vals['within_band_min']:+.2f}, {vals['within_band_max']:+.2f}]$"])
    tex.append(tabular(["Dataset", "Coreness rank", "Degree rank", "Clustering rank", "$|B_g|$",
                        r"Coreness $\rho_S$ range"], body_b, "lrrrrr"))

    body_c = []
    for ds in ORDER:
        best = min((r for r in pairs if r["dataset"] == ds), key=lambda r: float(r["rec_rel_diff"]))
        a, b = S.label(best["label_a"]), S.label(best["label_b"])
        size_a, size_b = float(best["rec_a"]) / 10, float(best["rec_b"]) / 10  # K|B_g| with K = 10
        cells += [cell(ID, ds, f"first:{a}", "bin_size", size_a, None, 0, panel="c"),
                  cell(ID, ds, f"first:{a}", "deg_eg", float(best["eg_a"]), None, 2, panel="c"),
                  cell(ID, ds, f"second:{b}", "bin_size", size_b, None, 0, panel="c"),
                  cell(ID, ds, f"second:{b}", "deg_eg", float(best["eg_b"]), None, 2, panel="c")]
        body_c.append([DATASET_LABEL[ds], f"[{a.replace('-', '--')}] vs. [{b.replace('-', '--')}]",
                       f"{size_a:,.0f} vs. {size_b:,.0f}",
                       f"${float(best['eg_a']):+.2f}$ vs. ${float(best['eg_b']):+.2f}$"])
    tex.append(tabular(["Dataset", "Bins", "$|B_g|$", "EG@10"], body_c, "llrr"))
    write_text("% Table 18 -- generated by `python -m reproduce build T18`\n" + "\n".join(tex), out / f"{ID}.tex")
    return cells
