"""Table 19 -- standardized coreness coefficients of per-user top-10 success (Appendix D).

Input: ``results_rq1_controls/diagnosis_conditional_v1/finalized/
diagnosis_coreness_coefficients_holm.csv`` from
``analysis/diagnosis_conditional_logit.py`` (job ``t19_conditional_logit.job``).
First line per dataset controls for log-degree; second adds local clustering.
"""
from reproduce.paths import resolve
from reproduce.table import DATASET_LABEL, cell, read_csv, tabular, write_text

ID = "T19"
INPUT = "results_rq1_controls/diagnosis_conditional_v1/finalized/diagnosis_coreness_coefficients_holm.csv"
ORDER = ["ego-facebook", "oklahoma", "unc", "pokec_n", "brightkite"]
METHODS = ["CN", "RA", "AA", "LightGCN", "HL-GNN"]
SPECS = {"degree": "degree_coreness", "degree_clustering": "degree_coreness_clustering"}


def input_files():
    return [INPUT]


def build(out):
    rows = {(r["dataset"], r["method"], r["specification"]): r for r in read_csv(resolve(INPUT))
            if r["coefficient"] == "z_coreness"}
    cells, body = [], []
    for ds in ORDER:
        for k, (panel, spec) in enumerate(SPECS.items()):
            line = [DATASET_LABEL[ds] if k == 0 else ""]
            for m in METHODS:
                r = rows[(ds, m, spec)]
                b, lo, hi = float(r["beta"]), float(r["ci95_low"]), float(r["ci95_high"])
                cells.append(cell(ID, ds, m, "coef", b, None, 2, panel=panel, extra=f"[{lo:+.2f}, {hi:+.2f}]"))
                line.append(f"${b:+.2f}$ $[{lo:+.2f}, {hi:+.2f}]$")
            body.append(line)
    write_text("% Table 19 -- generated by `python -m reproduce build T19`\n" +
               tabular(["Dataset"] + METHODS, body, "lrrrrr"), out / f"{ID}.tex")
    return cells
