"""Table 11 -- Equality Gain under acceptance models (Section 7.6, RQ6).

Full (every recommendation accepted), PW (precision-weighted acceptance) and
TP (true-positive acceptance) EG from ``core/acceptance_probe.py`` records.
All six numbers of a row come from the same runs; the fusion row is the
matched-beta control (HL-GNN+RA at CAFE-In's beta).  Mean +- population SD
over 10 fixed-split runs (RA: one deterministic run).
"""
import csv
from collections import defaultdict

from reproduce.loaders import jsonl, summarize
from reproduce.paths import SOURCES, resolve
from reproduce.table import DATASET_LABEL, DATASET_ORDER, cell, decorate, emphasis, fmt, tabular, write_text

ID = "T11"
ROWS = SOURCES / "acceptance_rows.csv"
COLUMNS = {"deg_full": "Degree_EG@10_full", "deg_pw": "Degree_EG@10_pw", "pr_full": "Pagerank_EG@10_full",
           "pr_pw": "Pagerank_EG@10_pw", "cl_full": "Closeness_EG@10_full", "cl_tp": "Closeness_EG@10_tp"}
METHODS = ["RA", "HL-GNN", "HL-GNN+RA", "CAFE-In", "CAFE-Pre"]
HEADER = ["Dataset", "Method", "Deg Full", "Deg PW", "PR Full", "PR PW", "Cl. Full", "Cl. TP"]


def sources():
    with open(ROWS) as fh:
        return list(csv.DictReader(fh))


def input_files():
    return sorted({r["source"] for r in sources()})


def _values(spec):
    if spec["format"] == "jsonl":
        records = [r for r in jsonl(spec["source"]) if not spec["config"] or r["config"] == spec["config"]]
        return {c: [r["acceptance"][k] for r in records] for c, k in COLUMNS.items()}
    per_metric = defaultdict(dict)
    with open(resolve(spec["source"])) as fh:
        for r in csv.DictReader(fh):
            if r["method"] == spec["method"]:
                per_metric[r["metric"]][int(float(r["run"]))] = float(r["value"])
    return {c: [v for _, v in sorted(per_metric[k].items())] for c, k in COLUMNS.items()}


def build(out):
    specs = {(s["dataset"], s["method"]): s for s in sources()}
    cells, body = [], []
    for ds in DATASET_ORDER:
        stats = {}
        for m in METHODS:
            vals = _values(specs[(ds, m)])
            n = 1 if m == "RA" else 10
            assert all(len(v) >= n for v in vals.values()), (ds, m, {k: len(v) for k, v in vals.items()})
            stats[m] = {c: summarize(v[:n]) for c, v in vals.items()}
            for c, s in stats[m].items():
                cells.append(cell(ID, ds, m, c, s["mean"], s["sd"], 2))
        marks = {c: emphasis([stats[m][c]["mean"] for m in METHODS]) for c in COLUMNS if c != "cl_tp"}
        if body:
            body.append("MIDRULE")
        for i, m in enumerate(METHODS):
            row = [DATASET_LABEL[ds] if i == 0 else "", m]
            for c in COLUMNS:
                s = stats[m][c]
                dec = 3 if c == "cl_tp" and abs(s["mean"]) < 1 else 2
                row.append(decorate(fmt(s["mean"], s["sd"], dec), marks.get(c, {}).get(i)))
            body.append(row)
    write_text("% Table 11 -- generated by `python -m reproduce build T11`\n" +
               tabular(HEADER, body, "llrrrrrr"), out / f"{ID}.tex")
    return cells
